/**
 * Generates src/lib/database.types.ts (supabase-js compatible) by introspecting DATABASE_URL.
 * Keeps TypeScript types in sync with SQL migrations without the Supabase CLI.
 */
import fs from "node:fs";
import pg from "pg";
import "dotenv/config";

const client = new pg.Client({ connectionString: process.env.DATABASE_URL });
await client.connect();

const pgToTs = (udt, dataType, enums) => {
  if (enums.has(udt)) return `Database["public"]["Enums"]["${udt}"]`;
  if (dataType === "ARRAY") {
    const inner = udt.replace(/^_/, "");
    return `${pgToTs(inner, "", enums)}[]`;
  }
  switch (udt) {
    case "uuid": case "text": case "varchar": case "bpchar": case "citext": case "date": case "timestamp": case "timestamptz": case "time": case "interval": case "bytea": case "name": case "inet":
      return "string";
    case "int2": case "int4": case "int8": case "float4": case "float8": case "numeric": case "oid":
      return "number";
    case "bool": return "boolean";
    case "json": case "jsonb": return "Json";
    default: return "unknown";
  }
};

const enumsRes = await client.query(`
  select t.typname, json_agg(e.enumlabel order by e.enumsortorder) as labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' group by t.typname order by t.typname`);
const enums = new Map(enumsRes.rows.map((r) => [r.typname, r.labels]));

const cols = await client.query(`
  select c.table_name, c.column_name, c.udt_name, c.data_type, c.is_nullable, c.column_default, c.is_generated, c.identity_generation,
         (select table_type from information_schema.tables t where t.table_schema = 'public' and t.table_name = c.table_name) as table_type
  from information_schema.columns c
  where c.table_schema = 'public' and c.table_name <> 'schema_migrations'
  order by c.table_name, c.ordinal_position`);

const tables = {};
for (const r of cols.rows) {
  tables[r.table_name] ??= { type: r.table_type, cols: [] };
  tables[r.table_name].cols.push(r);
}

const fns = await client.query(`
  select p.proname, pg_get_function_arguments(p.oid) as args, pg_get_function_result(p.oid) as result, p.proretset
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f'
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  order by p.proname`);

const tsType = (c) => pgToTs(c.udt_name, c.data_type, enums) + (c.is_nullable === "YES" ? " | null" : "");

let out = `// Generated by scripts/gen-db-types.mjs — do not edit by hand.\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n\nexport type Database = {\n  public: {\n    Tables: {\n`;
const views = [];
for (const [name, t] of Object.entries(tables)) {
  if (t.type === "VIEW") { views.push([name, t]); continue; }
  out += `      ${name}: {\n        Row: {\n`;
  for (const c of t.cols) out += `          ${c.column_name}: ${tsType(c)};\n`;
  out += `        };\n        Insert: {\n`;
  for (const c of t.cols) {
    if (c.is_generated === "ALWAYS" || c.identity_generation === "ALWAYS") continue;
    const optional = c.is_nullable === "YES" || c.column_default != null;
    out += `          ${c.column_name}${optional ? "?" : ""}: ${tsType(c)};\n`;
  }
  out += `        };\n        Update: {\n`;
  for (const c of t.cols) {
    if (c.is_generated === "ALWAYS" || c.identity_generation === "ALWAYS") continue;
    out += `          ${c.column_name}?: ${tsType(c)};\n`;
  }
  out += `        };\n        Relationships: [];\n      };\n`;
}
out += `    };\n    Views: {\n`;
for (const [name, t] of views) {
  out += `      ${name}: {\n        Row: {\n`;
  for (const c of t.cols) out += `          ${c.column_name}: ${tsType(c)};\n`;
  out += `        };\n        Relationships: [];\n      };\n`;
}
out += `    };\n    Functions: {\n`;
const parseArgs = (args) => {
  if (!args.trim()) return [];
  return args.split(",").map((a) => {
    const parts = a.trim().split(/\s+/);
    const name = parts[0];
    const type = parts.slice(1).join(" ");
    return { name, type };
  });
};
const sqlTypeToTs = (t) => {
  t = t.replace(/^public\./, "");
  const base = t.replace(/\[\]$/, "");
  const arr = t.endsWith("[]");
  let ts;
  if (enums.has(base)) ts = `Database["public"]["Enums"]["${base}"]`;
  else if (/^(uuid|text|date|timestamp.*|character varying)$/.test(base)) ts = "string";
  else if (/^(integer|bigint|smallint|numeric|double precision|real)$/.test(base)) ts = "number";
  else if (base === "boolean") ts = "boolean";
  else if (base === "jsonb" || base === "json") ts = "Json";
  else ts = "unknown";
  return arr ? `${ts}[]` : ts;
};
for (const f of fns.rows) {
  if (f.proname.startsWith("set_") || f.proname.startsWith("handle_") || f.proname.startsWith("guard_") || f.proname.startsWith("on_") || f.proname.includes("trigger") || f.result === "trigger") continue;
  const args = parseArgs(f.args);
  if (args.some((a) => !/^[a-z_][a-z0-9_]*$/i.test(a.name) || a.name === "OUT")) continue;
  const argTs = args.length ? `{ ${args.map((a) => `${a.name}: ${sqlTypeToTs(a.type)}`).join("; ")} }` : "Record<string, never>";
  let ret;
  const m = f.result.match(/^(SETOF )?TABLE\((.*)\)$/s);
  if (m) {
    const fields = m[2].split(",").map((x) => x.trim().split(/\s+/)).map(([n, ...t]) => `${n}: ${sqlTypeToTs(t.join(" "))}`);
    ret = `{ ${fields.join("; ")} }[]`;
  } else {
    ret = sqlTypeToTs(f.result.replace(/^SETOF /, ""));
    if (f.result === "void") ret = "undefined";
    if (f.proretset && !m) ret += "[]";
  }
  out += `      ${f.proname}: { Args: ${argTs}; Returns: ${ret} };\n`;
}
out += `    };\n    Enums: {\n`;
for (const [name, labels] of enums) out += `      ${name}: ${labels.map((l) => JSON.stringify(l)).join(" | ")};\n`;
out += `    };\n    CompositeTypes: Record<string, never>;\n  };\n};\n\n`;
out += `export type Tables<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Row"];\n`;
out += `export type TablesInsert<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Insert"];\n`;
out += `export type TablesUpdate<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Update"];\n`;
out += `export type Enums<T extends keyof Database["public"]["Enums"]> = Database["public"]["Enums"][T];\n`;
out += `export type Views<T extends keyof Database["public"]["Views"]> = Database["public"]["Views"][T]["Row"];\n`;
fs.writeFileSync("src/lib/database.types.ts", out);
await client.end();
console.log("wrote src/lib/database.types.ts");
